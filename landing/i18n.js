// === Apply translations ===
function applyI18n(lang) {
  const dict = I18N[lang] || I18N.en;
  document.documentElement.lang = lang === "cn" ? "zh-CN" : (lang === "id" ? "id" : "en");
  document.title = dict["meta.title"];
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.setAttribute("content", dict["meta.desc"]);

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(el => {
    const key = el.getAttribute("data-i18n-aria");
    if (dict[key] !== undefined) el.setAttribute("aria-label", dict[key]);
  });

  // Update language switcher state
  document.querySelectorAll(".lang-btn").forEach(btn => {
    const isActive = btn.dataset.lang === lang;
    btn.classList.toggle("active", isActive);
    btn.setAttribute("aria-pressed", isActive ? "true" : "false");
  });

  try { localStorage.setItem("sanak.lang", lang); } catch (e) {}
}

function initI18n() {
  let saved = null;
  try { saved = localStorage.getItem("sanak.lang"); } catch (e) {}
  const browser = (navigator.language || "en").toLowerCase();
  const detected = browser.startsWith("id") ? "id" : (browser.startsWith("zh") ? "cn" : "en");
  const initial = saved && I18N[saved] ? saved : detected;

  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.addEventListener("click", () => applyI18n(btn.dataset.lang));
  });

  applyI18n(initial);
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initI18n);
} else {
  initI18n();
}
